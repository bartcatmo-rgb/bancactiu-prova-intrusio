export function searchPredictiveCentresICS(query: string, maxResults: number = 8): CentreSanitari[] {
  if (!query || query.trim().length < 2) return [];
  const q = query.toLowerCase().trim();
  return CENS_OFICIAL_CENTRES_ICS.filter((c) =>
    c.nom.toLowerCase().includes(q) ||
    c.municipi.toLowerCase().includes(q) ||
    c.codiRecss.toLowerCase().includes(q) ||
    c.absNom.toLowerCase().includes(q) ||
    c.sectorNom.toLowerCase().includes(q) ||
    c.gerenciaNom.toLowerCase().includes(q)
  ).slice(0, maxResults);
}
